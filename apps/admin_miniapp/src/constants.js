// Лимит Telegram на подпись к медиа (caption) — 1024 символа. Текст рассылки и
// ответа в чате может уйти как caption (когда приложен файл), поэтому ограничиваем
// ввод этим значением, иначе при превышении бот ловит ошибку отправки молча
// («тихая» ошибка — пользователь ничего не видит).
export const MESSAGE_MAX_LENGTH = 1024

// Лимит Telegram на callback_data inline-кнопки — 64 БАЙТА (UTF-8), не символа.
// Кириллица/эмодзи весят 2–4 байта, поэтому символьный лимит дал бы ложный запас.
// При превышении бот молча роняет отправку — ограничиваем и валидируем заранее.
export const CALLBACK_DATA_MAX_BYTES = 64
